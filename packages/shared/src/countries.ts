export const countryCodes = Object.keys(countryNames) as [string, ...string[]];
export const countryCodeSchema = z.enum(countryCodes, {
  error: 'Gültiger ISO-Ländercode erforderlich (z. B. AT).',
});

const normalize = (s: string) =>
  s.normalize('NFKD').replace(/\p{M}/gu, '').replace(/[’‘]/g, "'").toLowerCase();
// Derive the code from a quoted country name, never from a portal's domain or
// the target property's country. English/German names are deterministic data.
export function countryFromEvidence(evidence: string): string | null {
  const text = normalize(evidence);
  const matches: { code: string; start: number; end: number }[] = [];
  for (const [code, names] of Object.entries(countryNames)) {
    for (const name of names) {
      const term = normalize(name);
      let start = text.indexOf(term);
      while (start !== -1) {
        const end = start + term.length;
        if (!/[\p{L}\p{N}]/u.test(text[start - 1] ?? '') && !/[\p{L}\p{N}]/u.test(text[end] ?? ''))
          matches.push({ code, start, end });
        start = text.indexOf(term, start + 1);
      }
    }
  }
  const codes = new Set(
    matches
      .filter(
        (m) =>
          !matches.some(
            (other) =>
              other.start <= m.start &&
              other.end >= m.end &&
              other.end - other.start > m.end - m.start,
          ),
      )
      .map((m) => m.code),
  );
  for (const match of evidence.matchAll(
    /(?:^|[^\p{L}])(?:country|land|iso(?:-3166)?)[\s:*=-]+([A-Z]{2})(?![A-Za-z])/giu,
  ))
    if (countryCodeSchema.safeParse(match[1]!.toUpperCase()).success)
      codes.add(match[1]!.toUpperCase());
  return codes.size === 1 ? [...codes][0]! : null;
}
